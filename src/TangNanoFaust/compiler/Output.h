// Build artifacts written by the faust2tang command line tool:
// - prog.hex           program memory image (40-bit words), $readmemh format
// - desc.hex           parameter descriptor (text, one byte per line)
// - config.vh          Verilog defines (memory sizes, the boot program)
// - <name>_params.h    C++ parameter indices for sketches
// - <name>_program.h   the compiled program for TangNanoFaust::load()
// - report.txt         memory layout, parameters and cycle budget
// Plain string building (no file I/O), so it is usable anywhere.
